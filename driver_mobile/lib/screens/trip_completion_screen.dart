class TripCompletionScreen extends StatefulWidget {
  final String tripId;
  final Map<String, dynamic>? tripData;

  const TripCompletionScreen({
    super.key,
    required this.tripId,
    this.tripData,
  });

  @override
  State<TripCompletionScreen> createState() => _TripCompletionScreenState();
}

class _TripCompletionScreenState extends State<TripCompletionScreen> {
  bool _isSubmitting = false;
  Map<String, dynamic>? _trip;

  // Local data holders
  Map<String, dynamic>? _podData;
  Map<String, dynamic>? _fuelData;
  Map<String, dynamic>? _weighbridgeData;
  Map<String, dynamic>? _tollData;

  @override
  void initState() {
    super.initState();
    _trip = widget.tripData;
    _fetchTripDetails();
    _fetchAutogeneratedTolls();
  }

  Future<void> _fetchTripDetails() async {
    final cleanId = widget.tripId.replaceAll('#', '').trim();
    try {
      final res = await ApiService.getTripDetails(cleanId);
      if (res != null && res['data'] != null) {
        setState(() {
          _trip = res['data'];
          if (_trip!['podDetails'] != null) {
            _podData = _trip!['podDetails'] as Map<String, dynamic>?;
          }
          if (_trip!['fuelDetails'] != null) {
            _fuelData = _trip!['fuelDetails'] as Map<String, dynamic>?;
          }
          if (_trip!['weighbridgeDetails'] != null) {
            _weighbridgeData = _trip!['weighbridgeDetails'] as Map<String, dynamic>?;
          }
          if (_trip!['tollDetails'] != null) {
            _tollData = _trip!['tollDetails'] as Map<String, dynamic>?;
          }
        });
      }
    } catch (_) {}
  }

  Future<void> _fetchAutogeneratedTolls() async {
    final cleanId = widget.tripId.replaceAll('#', '').trim();
    try {
      final res = await ApiService.getDriverTripTolls(cleanId);
      if (res != null && res['success'] == true) {
        final List list = res['data'] ?? [];
        if (list.isNotEmpty) {
          double total = 0.0;
          for (var item in list) {
            final amt = item['amountPaid'] ?? item['amount'] ?? 0.0;
            total += double.tryParse(amt.toString()) ?? 0.0;
          }
          final firstPlaza = list[0]['tollPlazaName'] ?? 'Toll Plaza';
          setState(() {
            _tollData = {
              'tollPlazaName': firstPlaza + (list.length > 1 ? ' + ${list.length - 1} more' : ''),
              'amountPaid': total,
              'dateTime': list[0]['dateTime'] ?? '',
              'isAutogenerated': true,
              'imageFiles': <dynamic>[],
              'imageNames': <String>[],
            };
          });
        }
      }
    } catch (_) {}
  }

  @override
  Widget build(BuildContext context) {
    final isDesktop = MediaQuery.of(context).size.width > 768;
    final cleanId = widget.tripId.replaceAll('#', '').trim();

    final isWeighbridgeRequired = _trip?['weighbridgeRequired'] ?? true;
    final podStatus = _podData != null ? 'Completed' : 'Pending';
    final fuelStatus = _fuelData != null ? 'Completed' : 'Pending';
    final weighbridgeStatus = !isWeighbridgeRequired
        ? 'Not Required'
        : (_weighbridgeData != null ? 'Completed' : 'Pending');
    final tollStatus = _tollData != null ? 'Completed' : 'Pending';

    return Scaffold(
      backgroundColor: AppColors.background,
      appBar: CustomAppBar(
        centerTitle: false,
        title: Text(
          'Trip Completion',
          style: Theme.of(context).textTheme.titleLarge?.copyWith(
            color: AppColors.background,
            fontWeight: FontWeight.bold,
          ),
        ),
      ),
      body: SafeArea(
        child: Stack(
          children: [
            SingleChildScrollView(
              padding: EdgeInsets.symmetric(
                horizontal: isDesktop ? MediaQuery.of(context).size.width * 0.2 : AppSpacing.md,
                vertical: AppSpacing.md,
              ),
              child: Column(
                crossAxisAlignment: CrossAxisAlignment.stretch,
                children: [
                  // Trip Summary Header Card
                  _buildSummaryHeader(),
                  const SizedBox(height: 20),

                  Text(
                    'COMPLETION CHECKLIST',
                    style: GoogleFonts.poppins(
                      fontSize: 11,
                      fontWeight: FontWeight.bold,
                      color: AppColors.secondaryText,
                      letterSpacing: 0.5,
                    ),
                  ),
                  const SizedBox(height: 8),

                  // 1. POD Card
                  _buildActionCard(
                    title: 'Proof of Delivery (POD)',
                    subtitle: _podData != null 
                        ? 'Customer Name: ${_podData!['customerName']}'
                        : 'Upload delivery receipt signed by customer',
                    icon: Icons.assignment_turned_in_rounded,
                    iconColor: Colors.blue,
                    status: podStatus,
                    onTap: () async {
                      final data = await Navigator.push(
                        context,
                        MaterialPageRoute(
                          builder: (context) => PodEntryScreen(initialData: _podData),
                        ),
                      );
                      if (data != null) {
                        setState(() {
                          _isSubmitting = true;
                        });
                        try {
                          await ApiService.uploadTripPod(
                            tripId: cleanId,
                            customerName: data['customerName'],
                            receiverName: data['receiverName'],
                            imageFile: data['imageFile'],
                            imageName: data['imageName'],
                          );
                          await _fetchTripDetails();
                          if (mounted) {
                            ScaffoldMessenger.of(context).showSnackBar(
                              const SnackBar(
                                content: Text('✅ POD uploaded successfully!'),
                                backgroundColor: AppColors.success,
                              ),
                            );
                          }
                        } catch (e) {
                          if (mounted) {
                            ScaffoldMessenger.of(context).showSnackBar(
                              SnackBar(
                                content: Text('POD upload failed: $e'),
                                backgroundColor: AppColors.error,
                              ),
                            );
                          }
                        } finally {
                          setState(() {
                            _isSubmitting = false;
                          });
                        }
                      }
                    },
                  ),
                  const SizedBox(height: 12),

                  // 2. Fuel Card
                  _buildActionCard(
                    title: 'Fuel Entry',
                    subtitle: _fuelData != null
                        ? '${_fuelData!['liters']} L refueled at ${_fuelData!['fuelStation']}'
                        : 'Enter trip refuel details and receipts',
                    icon: Icons.local_gas_station_rounded,
                    iconColor: Colors.orange,
                    status: fuelStatus,
                    onTap: () async {
                      final data = await Navigator.push(
                        context,
                        MaterialPageRoute(
                          builder: (context) => FuelEntryFormScreen(initialData: _fuelData),
                        ),
                      );
                      if (data != null) {
                        setState(() {
                          _isSubmitting = true;
                        });
                        try {
                          await ApiService.createTripFuelEntry(
                            fuelStation: data['fuelStation'],
                            amount: data['amount'],
                            liters: data['liters'],
                            odometer: data['odometer'],
                            tripId: cleanId,
                            dateTime: data['dateTime'],
                            imageFile: data['imageFile'],
                            imageName: data['imageName'],
                          );
                          await _fetchTripDetails();
                          if (mounted) {
                            ScaffoldMessenger.of(context).showSnackBar(
                              const SnackBar(
                                content: Text('✅ Fuel entry uploaded successfully!'),
                                backgroundColor: AppColors.success,
                              ),
                            );
                          }
                        } catch (e) {
                          if (mounted) {
                            ScaffoldMessenger.of(context).showSnackBar(
                              SnackBar(
                                content: Text('Fuel upload failed: $e'),
                                backgroundColor: AppColors.error,
                              ),
                            );
                          }
                        } finally {
                          setState(() {
                            _isSubmitting = false;
                          });
                        }
                      }
                    },
                  ),
                  const SizedBox(height: 12),

                  // Weighbridge Card
                  _buildActionCard(
                    title: 'Weighbridge Slip',
                    subtitle: !isWeighbridgeRequired
                        ? 'Weighbridge slip is not required for this trip'
                        : (_weighbridgeData != null
                            ? 'Net Weight: ${_weighbridgeData!['netWeight']} kg at ${_weighbridgeData!['location']}'
                            : 'Upload slip, tare, gross, and net weights'),
                    icon: Icons.scale_rounded,
                    iconColor: !isWeighbridgeRequired ? Colors.grey : Colors.purple,
                    status: weighbridgeStatus,
                    onTap: !isWeighbridgeRequired
                        ? () {}
                        : () async {
                            final data = await Navigator.push(
                              context,
                              MaterialPageRoute(
                                builder: (context) => WeighbridgeEntryScreen(initialData: _weighbridgeData),
                              ),
                            );
                            if (data != null) {
                              setState(() {
                                _isSubmitting = true;
                              });
                              try {
                                await ApiService.uploadWeighbridgeSlip(
                                  tripId: cleanId,
                                  grossWeight: data['grossWeight'],
                                  tareWeight: data['tareWeight'],
                                  netWeight: data['netWeight'],
                                  location: data['location'],
                                  imageFile: data['imageFile'],
                                  imageName: data['imageName'],
                                );
                                await _fetchTripDetails();
                                if (mounted) {
                                  ScaffoldMessenger.of(context).showSnackBar(
                                    const SnackBar(
                                      content: Text('✅ Weighbridge Slip uploaded successfully!'),
                                      backgroundColor: AppColors.success,
                                    ),
                                  );
                                }
                              } catch (e) {
                                if (mounted) {
                                  ScaffoldMessenger.of(context).showSnackBar(
                                    SnackBar(
                                      content: Text('Weighbridge upload failed: $e'),
                                      backgroundColor: AppColors.error,
                                    ),
                                  );
                                }
                              } finally {
                                setState(() {
                                  _isSubmitting = false;
                                });
                              }
                            }
                          },
                  ),
                  const SizedBox(height: 12),

                  // 3. Toll Card
                  _buildActionCard(
                    title: 'Toll Receipts',
                    subtitle: _tollData != null
                        ? (_tollData!['isAutogenerated'] == true
                            ? '₹${_tollData!['amountPaid']} automatically logged via FASTag'
                            : '₹${_tollData!['amountPaid']} paid at ${_tollData!['tollPlazaName']}')
                        : 'Upload receipts and amounts for tolls',
                    icon: Icons.toll_rounded,
                    iconColor: Colors.green,
                    status: tollStatus,
                    onTap: () async {
                      final result = await showDialog<String>(
                        context: context,
                        builder: (ctx) => TollTransactionsDialog(tripId: widget.tripId),
                      );

                      if (result == 'upload_manual') {
                        if (!mounted) return;
                        final data = await Navigator.push(
                          context,
                          MaterialPageRoute(
                            builder: (context) => TollReceiptsFormScreen(initialData: _tollData),
                          ),
                        );
                        if (data != null) {
                          setState(() {
                            _isSubmitting = true;
                          });
                          try {
                            await ApiService.createTripTollEntry(
                              tollPlazaName: data['tollPlazaName'],
                              amountPaid: data['amountPaid'],
                              tripId: cleanId,
                              dateTime: data['dateTime'],
                              imageFiles: data['imageFiles'],
                              imageNames: data['imageNames'],
                            );
                            await _fetchTripDetails();
                            if (mounted) {
                              ScaffoldMessenger.of(context).showSnackBar(
                                const SnackBar(
                                  content: Text('✅ Toll Receipt uploaded successfully!'),
                                  backgroundColor: AppColors.success,
                                ),
                              );
                            }
                          } catch (e) {
                            if (mounted) {
                              ScaffoldMessenger.of(context).showSnackBar(
                                SnackBar(
                                  content: Text('Toll upload failed: $e'),
                                  backgroundColor: AppColors.error,
                                ),
                              );
                            }
                          } finally {
                            setState(() {
                              _isSubmitting = false;
                            });
                          }
                        }
                      }
                    },
                  ),
                  const SizedBox(height: 32),

                  // Submit All Documents Button
                  ElevatedButton(
                    onPressed: _isSubmitting ? null : _handleSubmitAll,
                    style: ElevatedButton.styleFrom(
                      backgroundColor: AppColors.primary,
                      minimumSize: const Size(double.infinity, 48),
                      shape: RoundedRectangleBorder(
                        borderRadius: BorderRadius.circular(AppRadius.sm),
                      ),
                    ),
                    child: Text(
                      _isSubmitting ? 'UPLOADING...' : 'SUBMIT ALL DOCUMENTS',
                      style: GoogleFonts.poppins(
                        fontWeight: FontWeight.bold,
                        color: Colors.white,
                        fontSize: 14,
                      ),
                    ),
                  ),
                  const SizedBox(height: 40),
                ],
              ),
            ),
            if (_isSubmitting)
              Container(
                color: Colors.black.withValues(alpha: 0.5),
                child: const Center(
                  child: CircularProgressIndicator(color: AppColors.primary),
                ),
              ),
          ],
        ),
      ),
    );
  }

  Widget _buildSummaryHeader() {
    return CustomCard(
      padding: const EdgeInsets.all(16.0),
      child: Row(
        mainAxisAlignment: MainAxisAlignment.spaceBetween,
        children: [
          Column(
            crossAxisAlignment: CrossAxisAlignment.start,
            children: [
              Text(
                'TRIP ID',
                style: GoogleFonts.poppins(
                  fontSize: 10.5,
                  fontWeight: FontWeight.bold,
                  color: AppColors.secondaryText,
                ),
              ),
              const SizedBox(height: 4),
              Text(
                widget.tripId,
                style: GoogleFonts.poppins(
                  fontSize: 15,
                  fontWeight: FontWeight.bold,
                  color: AppColors.primaryText,
                ),
              ),
            ],
          ),
          Container(
            padding: const EdgeInsets.symmetric(horizontal: 10, vertical: 4),
            decoration: BoxDecoration(
              color: AppColors.success.withValues(alpha: 0.1),
              borderRadius: BorderRadius.circular(AppRadius.round),
            ),
            child: Text(
              'Awaiting Submissions',
              style: GoogleFonts.poppins(
                color: AppColors.success,
                fontWeight: FontWeight.bold,
                fontSize: 11,
              ),
            ),
          ),
        ],
      ),
    );
  }

  Widget _buildActionCard({
    required String title,
    required String subtitle,
    required IconData icon,
    required Color iconColor,
    required String status,
    required VoidCallback onTap,
  }) {
    final isCompleted = status == 'Completed';

    return GestureDetector(
      onTap: onTap,
      child: CustomCard(
        padding: const EdgeInsets.all(16.0),
        child: Row(
          children: [
            Container(
              width: 40,
              height: 40,
              decoration: BoxDecoration(
                color: iconColor.withValues(alpha: 0.1),
                borderRadius: BorderRadius.circular(8),
              ),
              child: Icon(icon, color: iconColor, size: 22),
            ),
            const SizedBox(width: 14),
            Expanded(
              child: Column(
                crossAxisAlignment: CrossAxisAlignment.start,
                children: [
                  Text(
                    title,
                    style: GoogleFonts.poppins(
                      fontSize: 13.5,
                      fontWeight: FontWeight.bold,
                      color: AppColors.primaryText,
                    ),
                  ),
                  const SizedBox(height: 2),
                  Text(
                    subtitle,
                    style: GoogleFonts.nunito(
                      fontSize: 11.5,
                      color: AppColors.secondaryText,
                    ),
                    maxLines: 1,
                    overflow: TextOverflow.ellipsis,
                  ),
                ],
              ),
            ),
            const SizedBox(width: 10),
            Container(
              padding: const EdgeInsets.symmetric(horizontal: 10, vertical: 4),
              decoration: BoxDecoration(
                color: isCompleted 
                    ? AppColors.success.withValues(alpha: 0.1)
                    : AppColors.secondary.withValues(alpha: 0.1),
                borderRadius: BorderRadius.circular(20),
              ),
              child: Row(
                children: [
                  if (isCompleted)
                    const Icon(Icons.check, size: 12, color: AppColors.success),
                  if (isCompleted)
                    const SizedBox(width: 4),
                  Text(
                    status,
                    style: GoogleFonts.poppins(
                      fontSize: 10.5,
                      fontWeight: FontWeight.bold,
                      color: isCompleted ? AppColors.success : AppColors.secondary,
                    ),
                  ),
                ],
              ),
            ),
          ],
        ),
      ),
    );
  }

  Future<void> _handleSubmitAll() async {
    if (_isSubmitting) return;

    final isWeighbridgeRequired = _trip?['weighbridgeRequired'] ?? true;
    final hasPod = _trip?['podDetails'] != null || _podData != null;
    final hasWeighbridge = !isWeighbridgeRequired || _trip?['weighbridgeDetails'] != null || _weighbridgeData != null;

    if (!hasPod) {
      ScaffoldMessenger.of(context).showSnackBar(
        const SnackBar(
          content: Text('⚠️ Proof of Delivery (POD) document is required.'),
          backgroundColor: AppColors.error,
        ),
      );
      return;
    }

    if (isWeighbridgeRequired && !hasWeighbridge) {
      ScaffoldMessenger.of(context).showSnackBar(
        const SnackBar(
          content: Text('⚠️ Weighbridge Slip document is required.'),
          backgroundColor: AppColors.error,
        ),
      );
      return;
    }

    setState(() {
      _isSubmitting = true;
    });

    final cleanId = widget.tripId.replaceAll('#', '').trim();

    try {
      // Update Trip Status to Completed
      await ApiService.updateTripStatus(cleanId, 'Completed');

      if (mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          const SnackBar(
            content: Text('🎉 Documents uploaded & Trip Completed successfully!'),
            backgroundColor: AppColors.success,
            behavior: SnackBarBehavior.floating,
          ),
        );
        Navigator.pop(context, true);
      }
    } catch (e) {
      if (mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(
            content: Text('Completion failed: ${e.toString().replaceAll('Exception: ', '')}'),
            backgroundColor: AppColors.error,
            behavior: SnackBarBehavior.floating,
          ),
        );
      }
    } finally {
      if (mounted) {
        setState(() {
          _isSubmitting = false;
        });
      }
    }
  }
}

