class WeighbridgeEntryScreen extends StatefulWidget {
  final Map<String, dynamic>? initialData;
  const WeighbridgeEntryScreen({super.key, this.initialData});

  @override
  State<WeighbridgeEntryScreen> createState() => _WeighbridgeEntryScreenState();
}

class _WeighbridgeEntryScreenState extends State<WeighbridgeEntryScreen> {
  final _formKey = GlobalKey<FormState>();
  final _grossController = TextEditingController();
  final _tareController = TextEditingController();
  final _netController = TextEditingController();
  final _locationController = TextEditingController();
  final _dateTimeController = TextEditingController();
  dynamic _imageBytes;
  String? _imageName;

  @override
  void initState() {
    super.initState();
    _dateTimeController.text = DateTime.now().toString().split('.')[0];
    _grossController.addListener(_updateNetWeight);
    _tareController.addListener(_updateNetWeight);

    if (widget.initialData != null) {
      _grossController.text = widget.initialData!['grossWeight']?.toString() ?? '';
      _tareController.text = widget.initialData!['tareWeight']?.toString() ?? '';
      _netController.text = widget.initialData!['netWeight']?.toString() ?? '';
      _locationController.text = widget.initialData!['location'] ?? '';
      _dateTimeController.text = widget.initialData!['dateTime'] ?? '';
      _imageBytes = widget.initialData!['imageFile'];
      _imageName = widget.initialData!['imageName'];
    }
  }

  void _updateNetWeight() {
    final gross = double.tryParse(_grossController.text) ?? 0.0;
    final tare = double.tryParse(_tareController.text) ?? 0.0;
    final net = gross - tare;
    if (net >= 0) {
      _netController.text = net.toStringAsFixed(1);
    } else {
      _netController.text = '0.0';
    }
  }

  @override
  void dispose() {
    _grossController.removeListener(_updateNetWeight);
    _tareController.removeListener(_updateNetWeight);
    _grossController.dispose();
    _tareController.dispose();
    _netController.dispose();
    _locationController.dispose();
    _dateTimeController.dispose();
    super.dispose();
  }

  Future<void> _pickImage() async {
    final XFile? file = await ImagePicker().pickImage(source: ImageSource.gallery, imageQuality: 85);
    if (file != null) {
      final bytes = await file.readAsBytes();
      setState(() {
        _imageBytes = bytes;
        _imageName = file.name;
      });
    }
  }

