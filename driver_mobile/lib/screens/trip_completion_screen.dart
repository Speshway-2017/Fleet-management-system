                controller: _receiverController,
                label: 'Receiver Name',
                hint: 'e.g. John Doe',
                validator: (val) => val == null || val.trim().isEmpty ? 'Receiver Name is required' : null,
              ),
              const SizedBox(height: 20),
              Text(
                'PROOF OF DELIVERY SLIP',
                style: GoogleFonts.poppins(
                  fontSize: 10.5,
                  fontWeight: FontWeight.bold,
                  color: AppColors.secondaryText,
                ),
              ),
              const SizedBox(height: 8),
              _imageBytes == null
                  ? InkWell(
                      onTap: _pickImage,
                      child: Container(
                        height: 120,
                        decoration: BoxDecoration(
                          border: Border.all(color: AppColors.divider),
                          borderRadius: BorderRadius.circular(AppRadius.md),
                          color: Colors.grey.shade50,
                        ),
                        child: Center(
                          child: Column(
                            mainAxisAlignment: MainAxisAlignment.center,
                            children: [
                              const Icon(Icons.add_photo_alternate_outlined, color: AppColors.secondary, size: 28),
                              const SizedBox(height: 6),
                              Text('Tap to select POD receipt', style: GoogleFonts.nunito(fontSize: 12, color: AppColors.secondaryText)),
                            ],
                          ),
                        ),
                      ),
                    )
                  : Container(
                      height: 120,
                      decoration: BoxDecoration(
                        border: Border.all(color: AppColors.divider),
                        borderRadius: BorderRadius.circular(AppRadius.md),
                      ),
                      padding: const EdgeInsets.all(8),
                      child: Row(
                        children: [
                          const Icon(Icons.description_outlined, color: Colors.blue, size: 36),
                          const SizedBox(width: 12),
                          Expanded(
                            child: Column(
                              crossAxisAlignment: CrossAxisAlignment.start,
                              mainAxisAlignment: MainAxisAlignment.center,
                              children: [
                                Text(
                                  _imageName ?? 'pod_receipt.jpg',
                                  style: GoogleFonts.poppins(fontSize: 13, fontWeight: FontWeight.bold, color: AppColors.primaryText),
                                  maxLines: 1,
                                  overflow: TextOverflow.ellipsis,
                                ),
                                const SizedBox(height: 4),
                                Text('Attached successfully', style: GoogleFonts.nunito(fontSize: 11, color: AppColors.success)),
                              ],
