  List<dynamic> _fastagTolls = [];
  double _totalAmount = 0.0;
  String? _errorMessage;

  @override
  void initState() {
    super.initState();
    _fetchTolls();
  }

  Future<void> _fetchTolls() async {
    final cleanId = widget.tripId.replaceAll('#', '').trim();
    try {
      final res = await ApiService.getDriverTripTolls(cleanId);
      if (res != null && res['success'] == true) {
        final List list = res['data'] ?? [];
        final fastagList = list.where((item) => item['paymentMethod'] == 'FASTag').toList();
        
        double total = 0.0;
        for (var item in fastagList) {
          final amt = item['amountPaid'] ?? item['amount'] ?? 0.0;
          total += double.tryParse(amt.toString()) ?? 0.0;
        }

        if (mounted) {
          setState(() {
            _fastagTolls = fastagList;
            _totalAmount = total;
            _isLoading = false;
          });
        }
      } else {
        if (mounted) {
          setState(() {
            _isLoading = false;
          });
        }
      }
    } catch (e) {
      if (mounted) {
        setState(() {
          _errorMessage = e.toString().replaceAll('Exception: ', '');
          _isLoading = false;
        });
      }
    }
