class _PodEntryScreenState extends State<PodEntryScreen> {
  final _formKey = GlobalKey<FormState>();
  final _customerController = TextEditingController(text: 'Acme Logistics');
  final _receiverController = TextEditingController(text: 'Verified Receiver');
  dynamic _imageBytes;
  String? _imageName;

  @override
  void initState() {
    super.initState();
    if (widget.initialData != null) {
      _customerController.text = widget.initialData!['customerName'] ?? '';
      _receiverController.text = widget.initialData!['receiverName'] ?? '';
