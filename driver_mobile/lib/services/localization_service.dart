class LocalizationService {
  static const String defaultLanguage = 'English (US)';
  
  static final ValueNotifier<String> currentLanguageNotifier =
      ValueNotifier<String>(defaultLanguage);

  static String get currentLanguage => currentLanguageNotifier.value;

  static String normalizeLanguage(String? lang) {
    if (lang == null || lang.trim().isEmpty) return defaultLanguage;
    final trimmed = lang.trim();
    final lower = trimmed.toLowerCase();
    if (lower == 'english' ||
        lower == 'en' ||
        lower == 'en_us' ||
        lower == 'en-us') {
      return defaultLanguage;
    }
    if (lower == 'hindi' || lower == 'hi') return 'Hindi';
    if (lower == 'spanish' || lower == 'es') return 'Spanish';
    if (lower == 'french' || lower == 'fr') return 'French';
    if (lower == 'german' || lower == 'de') return 'German';
    return trimmed;
  }

  static Future<void> init() async {
    try {
      final prefs = await SharedPreferences.getInstance();
      final saved = prefs.getString('app_language');
      if (saved != null && saved.isNotEmpty) {
        currentLanguageNotifier.value = normalizeLanguage(saved);
      }
    } catch (e) {
      debugPrint('[LocalizationService] Error loading language: $e');
    }
  }

  static void setLanguage(String lang) {
    final normalized = normalizeLanguage(lang);
    if (currentLanguageNotifier.value != normalized) {
      currentLanguageNotifier.value = normalized;
    }
  }

  static String tr(String key) {
    final lang = currentLanguageNotifier.value;
    final langMap = _localizedValues[lang];
    if (langMap != null && langMap.containsKey(key)) {
      return langMap[key]!;
    }
    // Fallback to English (US)
    final enMap = _localizedValues[defaultLanguage];
    if (enMap != null && enMap.containsKey(key)) {
      return enMap[key]!;
    }
    return key;
  }

