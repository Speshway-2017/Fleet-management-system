/// Centralized localization service for Fleet Driver Mobile.
/// Translates app interface texts dynamically across all pages into
/// English, Hindi, Spanish, French, and German in real time.
class LocalizationService {
  static const String defaultLanguage = 'English (US)';

  static const List<String> supportedLanguages = [
    'English (US)',
    'Hindi',
    'Spanish',
    'French',
    'German',
  ];
  
  static final ValueNotifier<String> currentLanguageNotifier =
      ValueNotifier<String>(defaultLanguage);

  static String get currentLanguage => currentLanguageNotifier.value;

  static Locale getLocale(String lang) {
    final normalized = normalizeLanguage(lang);
    switch (normalized) {
      case 'Hindi':
        return const Locale('hi', 'IN');
      case 'Spanish':
        return const Locale('es', 'ES');
      case 'French':
        return const Locale('fr', 'FR');
      case 'German':
        return const Locale('de', 'DE');
      case 'English (US)':
      default:
        return const Locale('en', 'US');
    }
  }

  static Locale get currentLocale => getLocale(currentLanguage);

  static String normalizeLanguage(String? lang) {
    if (lang == null || lang.trim().isEmpty) return defaultLanguage;
    final trimmed = lang.trim();
    final lower = trimmed.toLowerCase();
    if (lower == 'english' ||
        lower == 'en' ||
        lower == 'en_us' ||
        lower == 'en-us' ||
        lower == 'english (us)' ||
        lower.startsWith('en')) {
      return defaultLanguage;
    }
    if (lower == 'hindi' || lower == 'hi' || lower == 'hi_in' || lower.contains('हिन्दी')) {
      return 'Hindi';
    }
    if (lower == 'spanish' ||
        lower == 'es' ||
        lower == 'es_es' ||
        lower.contains('español') ||
        lower.contains('espanol')) {
      return 'Spanish';
    }
    if (lower == 'french' ||
        lower == 'fr' ||
        lower == 'fr_fr' ||
        lower.contains('français') ||
        lower.contains('francais')) {
      return 'French';
    }
    if (lower == 'german' ||
        lower == 'de' ||
        lower == 'de_de' ||
        lower.contains('deutsch')) {
      return 'German';
    }
    return defaultLanguage;
  }

  static Future<void> init() async {
    try {
      final prefs = await SharedPreferences.getInstance();
      final saved = prefs.getString('app_language');
      if (saved != null && saved.isNotEmpty) {
        currentLanguageNotifier.value = normalizeLanguage(saved);
      }
    } catch (e) {
      debugPrint('[LocalizationService] Error loading language: $e');
    }
  }

  static void setLanguage(String lang) {
    final normalized = normalizeLanguage(lang);
    if (currentLanguageNotifier.value != normalized) {
      currentLanguageNotifier.value = normalized;
    }
    SharedPreferences.getInstance().then((prefs) {
      prefs.setString('app_language', normalized);
    }).catchError((_) {});
  }

  static String tr(String key) {
    if (key.isEmpty) return key;
    final lang = normalizeLanguage(currentLanguageNotifier.value);
    final langMap = _localizedValues[lang];
    if (langMap != null) {
      if (langMap.containsKey(key)) {
        return langMap[key]!;
      }
      final trimmed = key.trim();
      if (trimmed.isNotEmpty && langMap.containsKey(trimmed)) {
        final startIdx = key.indexOf(trimmed);
        final prefix = key.substring(0, startIdx);
        final suffix = key.substring(startIdx + trimmed.length);
        return '${prefix}${langMap[trimmed]!}${suffix}';
      }
    }
    // Fallback to English (US)
    final enMap = _localizedValues[defaultLanguage];
    if (enMap != null) {
      if (enMap.containsKey(key)) {
        return enMap[key]!;
      }
      final trimmed = key.trim();
      if (trimmed.isNotEmpty && enMap.containsKey(trimmed)) {
        final startIdx = key.indexOf(trimmed);
        final prefix = key.substring(0, startIdx);
        final suffix = key.substring(startIdx + trimmed.length);
        return '${prefix}${enMap[trimmed]!}${suffix}';
      }
    }
    return key;
  }

